// Generates the old man's voice with ElevenLabs, one take per line with character
// timestamps, and assembles the film's timeline from them.
//
//   NODE_USE_ENV_PROXY=1 node sandbox/2026-11-12-donde-miro/gen-voice.mjs [--voice <id>] [--only id,id] [--name voice]
//
// Takes are cached in private/audio/ by a hash of text + voice + settings (never
// committed). Out: private/audio/<name>.wav (the whole track), timeline.js (line and word
// times, loaded by the scene: every cut and every look comes from it) and mix.wav.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const dir = path.dirname(fileURLToPath(import.meta.url)), A = path.join(dir, 'private/audio');
const arg = (k, d) => { const i = process.argv.indexOf('--' + k); return i > 0 ? process.argv[i + 1] : d; };
const V = JSON.parse(fs.readFileSync(path.join(dir, 'voice.json'), 'utf8'));
const voice = arg('voice', V.voice_id), name = arg('name', 'voice'), only = arg('only', null)?.split(',');
const key = process.env.ELEVEN_KEY ?? process.env.ELEVENLABS_API_KEY ?? 'proxy';
fs.mkdirSync(A, { recursive: true });

const lines = V.lines.filter((l) => !only || only.includes(l.id));
const takes = [];
for (const [i, l] of lines.entries()) {
    const body = { text: l.text, model_id: V.model_id, voice_settings: V.settings, previous_text: lines[i - 1]?.text, next_text: lines[i + 1]?.text };
    const h = crypto.createHash('sha1').update(JSON.stringify([voice, body])).digest('hex').slice(0, 10);
    const base = path.join(A, `${l.id}-${h}`);
    if (!fs.existsSync(base + '.json')) {
        const res = await fetch(`https://api.elevenlabs.io/v1/text-to-speech/${voice}/with-timestamps?output_format=mp3_44100_128`, { method: 'POST', headers: { 'xi-api-key': key, 'Content-Type': 'application/json' }, body: JSON.stringify(body) });
        if (!res.ok) { console.error(l.id, res.status, (await res.text()).slice(0, 300)); process.exit(1); }
        const j = await res.json();
        fs.writeFileSync(base + '.mp3', Buffer.from(j.audio_base64, 'base64'));
        fs.writeFileSync(base + '.json', JSON.stringify(j.alignment));
        console.log('generated', l.id);
    }
    const al = JSON.parse(fs.readFileSync(base + '.json', 'utf8'));
    // words from the character times; the take's spoken span is first to last letter
    const words = [];
    let w = null;
    al.characters.forEach((c, k) => {
        if (/[\p{L}\p{N}]/u.test(c)) {
            if (!w) w = { w: '', a: al.character_start_times_seconds[k], b: 0 };
            w.w += c;
            w.b = al.character_end_times_seconds[k];
        } else if (w) { words.push(w); w = null; }
    });
    if (w) words.push(w);
    const dur = Number(execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', base + '.mp3']).toString());
    takes.push({ ...l, file: base + '.mp3', words, a: words[0].a, b: words[words.length - 1].b, dur });
}

// place the takes: each starts when the one before stops speaking, plus its gap
let t = V.start;
const tl = [];
for (const k of takes) {
    const at = t - k.a; // the file's zero in film time
    tl.push({ id: k.id, text: k.text, t0: +t.toFixed(3), t1: +(t + k.b - k.a).toFixed(3), words: k.words.map((x) => [x.w, +(at + x.a).toFixed(3), +(at + x.b).toFixed(3)]), at, file: k.file });
    t += k.b - k.a + k.gap;
}
const duration = Math.ceil((tl[tl.length - 1].t1 + V.tail) * 2) / 2;
const out = path.join(A, name + '.wav');
const inputs = tl.flatMap((k) => ['-i', k.file]);
const graph = tl.map((k, i) => `[${i}]adelay=${Math.max(0, Math.round(k.at * 1000))}:all=1[a${i}]`).join(';') + ';' + tl.map((_, i) => `[a${i}]`).join('') + `amix=inputs=${tl.length}:normalize=0:duration=longest,apad=whole_dur=${duration}[o]`;
execFileSync('ffmpeg', ['-v', 'error', '-y', ...inputs, '-filter_complex', graph, '-map', '[o]', '-t', String(duration), '-ar', '48000', out]);
if (!only && name === 'voice') {
    fs.copyFileSync(out, path.join(dir, 'mix.wav'));
    const pub = tl.map(({ id, text, t0, t1, words }) => ({ id, text, t0, t1, words }));
    fs.writeFileSync(path.join(dir, 'timeline.js'), `// Generated by gen-voice.mjs from voice.json: when each line and each word is said.\n// The scene takes every cut and every look from here. Do not edit by hand.\nconst Voice = ${JSON.stringify({ voice: V.voice_name, duration, lines: pub }, null, 1)};\n`);
}
console.log(out, '·', duration, 's');
for (const k of tl) console.log(k.t0.toFixed(2).padStart(6), k.t1.toFixed(2).padStart(6), k.id.padEnd(8), k.text);
