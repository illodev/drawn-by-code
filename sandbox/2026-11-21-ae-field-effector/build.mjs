// build.mjs - joins effector-ae.jsx with the expression sources (field-math.js,
// field-glue.js) into FieldEffector.jsx, the one file a designer runs in After Effects
// (File > Scripts > Run Script File, or the Scripts folder).
//
//   node sandbox/2026-11-21-ae-field-effector/build.mjs
//
// It lints the three sources for what ExtendScript (ES3) cannot parse, since a syntax
// error there only shows up as an alert inside After Effects, and checks that the
// expression sources are ASCII (they are pasted into every target's expressions).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = path.dirname(fileURLToPath(import.meta.url));
const read = (f) => fs.readFileSync(path.join(dir, f), 'utf8').replace(/\r\n/g, '\n');
const math = read('field-math.js');
const glue = read('field-glue.js');
const ae = read('effector-ae.jsx');

const problems = [];
for (const [file, src] of [['field-math.js', math], ['field-glue.js', glue], ['effector-ae.jsx', ae]]) {
    src.split('\n').forEach((line, n) => {
        const code = line.replace(/\/\/.*$/, '').replace(/'(?:[^'\\]|\\.)*'|"(?:[^"\\]|\\.)*"/g, "''");
        const hits = [
            [/\b(let|const|class)\s/, 'let/const/class'],
            [/=>/, 'arrow function'],
            [/`/, 'template literal'],
            [/\.(forEach|map|filter|reduce|some|every|includes|find|findIndex|indexOf)\(/, 'ES5+ array method'],
            [/\b(JSON|Object\.keys|Array\.isArray|Math\.(sign|hypot|trunc|imul|cbrt|log2|log10))\b/, 'ES5+ global'],
            [/,\s*[}\]]/, 'trailing comma'],
        ];
        for (const [re, what] of hits) {
            if (what === 'ES5+ array method' && /\.indexOf\(/.test(code) && file === 'effector-ae.jsx') continue; // strings only there
            if (re.test(code)) problems.push(`${file}:${n + 1}: ${what}: ${line.trim()}`);
        }
        if (file !== 'effector-ae.jsx' && /[^\x00-\x7f]/.test(line)) problems.push(`${file}:${n + 1}: non-ASCII character (it goes into expressions)`);
    });
    const flat = src.replace(/\/\/.*$/gm, '');
    if (/,\s*\n\s*[}\]]/.test(flat)) problems.push(`${file}: trailing comma before a closing bracket on the next line`);
}
if (problems.length) {
    console.error('ES3 problems:\n' + problems.join('\n'));
    process.exit(1);
}

// what goes into the expressions: no comments, no blank lines
const strip = (src) => src.split('\n').map((l) => l.replace(/\s*\/\/.*$/, '')).filter((l) => l.trim()).join('\n');
const MATH = strip(math), GLUE = strip(glue);
new Function(MATH + '\n' + GLUE); // syntax check

let body = ae
    .replace("var FX_MATH = '';", 'var FX_MATH = ' + JSON.stringify(MATH) + ';')
    .replace("var FX_GLUE = '';", 'var FX_GLUE = ' + JSON.stringify(GLUE) + ';')
    .replace('if (!$.global.FX_NO_UI) FieldEffector.run();', '$.global.FieldEffector = FieldEffector;\nif (!$.global.FX_NO_UI) FieldEffector.run();');
if (body.indexOf('var FX_MATH = "') < 0 || body.indexOf('var FX_GLUE = "') < 0) {
    console.error('build: the FX_MATH / FX_GLUE placeholders were not found in effector-ae.jsx');
    process.exit(1);
}

const out = [
    '// FieldEffector.jsx - a MoGraph-style field effector for After Effects: a null you key makes',
    '// every layer it passes over scale, move, turn, fade, tint or scrub, live through expressions.',
    '// Generated by build.mjs from effector-ae.jsx + field-math.js + field-glue.js: edit those, then rebuild.',
    '// Usage: README.md next to this file.',
    '(function () {',
    body,
    '})();',
    '',
].join('\n');
new Function(out.replace(/\$\.global/g, '({})')); // syntax check only, nothing runs
fs.writeFileSync(path.join(dir, 'FieldEffector.jsx'), out);
console.log(`FieldEffector.jsx · ${out.length} bytes · expression math ${MATH.length + GLUE.length} bytes`);
