# Turns a word-level transcription of the track (private/words.json: ElevenLabs speech-to-text,
# word timestamps) into what the film needs, without the words themselves: for every sung word
# its start, its end and a mouth shape (A wide, E half, O round), and the times of the phrase
# that is the song's title. Prints a JavaScript block to paste between the VOCALS markers of
# song.js (python3 tools/make-vocals.py --write does it).
#   python3 tools/make-vocals.py [--write]
import json, os, re, sys
here = os.path.dirname(os.path.abspath(__file__)); root = os.path.dirname(here)
words = [w for w in json.load(open(os.path.join(root, 'private', 'words.json')))['words'] if w.get('type') == 'word']
def shape(text):
    t = re.sub(r"[^a-z']", '', text.lower())
    m = re.search(r'[aeiouy]+', t)
    v = m.group(0) if m else 'a'
    if t in ('i', "i'm", 'my', 'mine', 'eyes', 'by', 'time', 'like', 'sky', 'sunshine', 'flying', 'driving', 'wild', 'mine'): return 'A'
    if v[0] in 'ou' or v in ('ow',): return 'O'
    if v[0] in 'ey' or v in ('ea', 'ee', 'ie'): return 'E'
    if v[0] == 'i': return 'E'
    return 'A'
rows = [[round(w['start'], 2), round(w['end'], 2), shape(w['text'])] for w in words]
low = [re.sub(r"[^a-z']", '', w['text'].lower()) for w in words]
titles = []
for i in range(len(low) - 3):
    if low[i] == 'running' and low[i+1] == 'down' and low[i+2] == 'a' and low[i+3] == 'dream':
        titles.append([rows[i][0], rows[i+1][0], rows[i+3][0], rows[i+3][1]])
js = '    // VOCALS:BEGIN (generated by tools/make-vocals.py from a transcription; times in seconds)\n'
js += '    // every sung word of the lead: [start, end, mouth shape]\n    const WORDS = [' + ', '.join(f"[{a}, {b}, '{c}']" for a, b, c in rows) + '];\n'
js += "    // each time the title is sung: [«runnin'», «down», «dream», the phrase's end]\n    const TITLES = " + json.dumps(titles) + ';\n'
js += '    // VOCALS:END\n'
if '--write' in sys.argv:
    p = os.path.join(root, 'song.js'); s = open(p).read()
    a, b = s.index('    // VOCALS:BEGIN'), s.index('    // VOCALS:END\n') + len('    // VOCALS:END\n')
    open(p, 'w').write(s[:a] + js + s[b:]); print('song.js updated:', len(rows), 'words,', len(titles), 'titles')
else:
    print(js)
for t in titles: print('title', t)
